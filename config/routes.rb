Rails.application.routes.draw do
  root 'pages#index'
  get '/login', to: 'pages#login'
  get '/register', to: 'pages#register'
  get '/app', to: 'pages#workspace'
  namespace :api do
    get '/csrf', to: 'auth#csrf'
    post '/auth/register', to: 'auth#register'
    post '/auth/login', to: 'auth#login'
    post '/auth/logout', to: 'auth#logout'
    get '/me', to: 'auth#me'
    patch '/profile', to: 'profile#update'
    get '/profile/reviews', to: 'profile#reviews'
    post '/onboarding/complete', to: 'profile#complete_onboarding'
    get '/categories', to: 'catalog#categories'
    get '/skills', to: 'catalog#skills'
    get '/my-skills', to: 'my_skills#index'
    post '/my-skills', to: 'my_skills#create'
    patch '/my-skills/:id', to: 'my_skills#update'
    delete '/my-skills/:id', to: 'my_skills#destroy'
    get '/explore', to: 'matches#explore'
    get '/matches', to: 'matches#index'
    get '/partners/:id', to: 'matches#partner'
    get '/exchanges', to: 'exchanges#index'
    post '/exchanges', to: 'exchanges#create'
    patch '/exchanges/:id', to: 'exchanges#update'
    get '/sessions', to: 'sessions#index'
    post '/sessions', to: 'sessions#create'
    patch '/sessions/:id', to: 'sessions#update'
    post '/sessions/:id/reviews', to: 'sessions#review'
    get '/notifications', to: 'notifications#index'
    patch '/notifications/:id', to: 'notifications#update'
    post '/notifications/read-all', to: 'notifications#read_all'
    get '/dashboard', to: 'dashboard#show'
    namespace :admin do
      get '/overview', to: 'dashboard#overview'
      get '/users', to: 'users#index'
      get '/users/:id', to: 'users#show'
      patch '/users/:id', to: 'users#update'
      post '/categories', to: 'categories#create'
      patch '/categories/:id', to: 'categories#update'
      delete '/categories/:id', to: 'categories#destroy'
      get '/exchanges', to: 'reports#exchanges'
      get '/reports', to: 'reports#show'
    end
  end
end
